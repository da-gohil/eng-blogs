#!/usr/bin/env node
/**
 * Downloads a favicon (at least 32×32) for every domain in the catalog into
 * public/icons/ and writes src/data/icons.generated.js, which maps each domain
 * to its icon file.
 *
 * Icons are committed to the repo, so the deployed site never hot-links a
 * third-party service, and cards without an icon fall back to a monogram.
 *
 *   npm run icons            # fetch icons that are missing
 *   npm run icons -- --force # refetch everything
 *   npm run icons -- --prune # also delete icons that are no longer used
 */
import { existsSync } from "node:fs";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { RESOURCES } from "../src/data/resources/index.js";
import { iconDomain } from "../src/lib/format.js";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ICON_DIR = `${ROOT}public/icons`;
const MANIFEST = `${ROOT}src/data/icons.generated.js`;
const MIN_SIZE = 32;
const force = process.argv.includes("--force");
const prune = process.argv.includes("--prune");

const startsWith = (bytes, signature) => signature.every((byte, i) => bytes[i] === byte);
const view = (bytes) => new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);

/** Returns { ext, width } for PNG and JPEG data, or null for anything else. */
function imageInfo(bytes) {
  if (bytes.length < 24) return null;
  if (startsWith(bytes, [0x89, 0x50, 0x4e, 0x47])) return { ext: "png", width: view(bytes).getUint32(16) };
  if (startsWith(bytes, [0xff, 0xd8])) {
    // Walk JPEG segments until a start-of-frame marker, which holds the size.
    for (let i = 2; i + 9 <= bytes.length; ) {
      if (bytes[i] !== 0xff) return null;
      const marker = bytes[i + 1];
      const length = view(bytes).getUint16(i + 2);
      const isFrame = marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker);
      if (isFrame) return { ext: "jpg", width: view(bytes).getUint16(i + 7) };
      i += 2 + length;
    }
  }
  return null;
}

/** Extracts the largest PNG embedded in an .ico file, if there is one. */
function pngFromIco(bytes) {
  if (bytes.length < 6 || !startsWith(bytes, [0, 0, 1, 0])) return null;
  const count = view(bytes).getUint16(4, true);
  let best = null;
  for (let i = 0; i < count && 6 + (i + 1) * 16 <= bytes.length; i++) {
    const entry = 6 + i * 16;
    const size = view(bytes).getUint32(entry + 8, true);
    const offset = view(bytes).getUint32(entry + 12, true);
    if (offset + size > bytes.length) continue;
    const image = bytes.subarray(offset, offset + size);
    const info = imageInfo(image);
    if (info?.ext === "png" && (!best || info.width > best.info.width)) best = { image, info };
  }
  return best;
}

async function download(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(15_000) });
  return response.ok ? new Uint8Array(await response.arrayBuffer()) : null;
}

async function fetchIcon(domain) {
  const google = await download(`https://www.google.com/s2/favicons?domain=${encodeURIComponent(domain)}&sz=64`);
  const googleInfo = google && imageInfo(google);
  if (googleInfo?.width >= MIN_SIZE) return { bytes: google, ext: googleInfo.ext };

  const ddg = await download(`https://icons.duckduckgo.com/ip3/${encodeURIComponent(domain)}.ico`);
  if (!ddg) return null;
  const direct = imageInfo(ddg);
  if (direct?.width >= MIN_SIZE) return { bytes: ddg, ext: direct.ext };
  const embedded = pngFromIco(ddg);
  if (embedded?.info.width >= MIN_SIZE) return { bytes: embedded.image, ext: "png" };
  return null;
}

const domains = [...new Set(RESOURCES.map(iconDomain).filter(Boolean))].sort();
await mkdir(ICON_DIR, { recursive: true });
const existing = new Set(await readdir(ICON_DIR));

/** @type {Record<string, string>} domain -> file name */
const manifest = {};
const missing = [];
for (const domain of domains) {
  const cached = ["png", "jpg"].map((ext) => `${domain}.${ext}`).find((file) => existing.has(file));
  if (cached && !force) {
    manifest[domain] = cached;
    continue;
  }
  try {
    const icon = await fetchIcon(domain);
    if (!icon) {
      missing.push(domain);
      continue;
    }
    const file = `${domain}.${icon.ext}`;
    if (cached && cached !== file) await rm(`${ICON_DIR}/${cached}`);
    await writeFile(`${ICON_DIR}/${file}`, icon.bytes);
    manifest[domain] = file;
  } catch (error) {
    missing.push(`${domain} (${error.name})`);
  }
}

if (prune) {
  const keep = new Set(Object.values(manifest));
  for (const file of await readdir(ICON_DIR)) {
    if (/\.(png|jpg)$/.test(file) && !keep.has(file) && existsSync(`${ICON_DIR}/${file}`)) {
      await rm(`${ICON_DIR}/${file}`);
    }
  }
}

await writeFile(
  MANIFEST,
  `// Generated by scripts/fetch-icons.mjs — do not edit by hand.\n` +
    `export const ICONS = ${JSON.stringify(manifest, null, 2)};\n`,
);

console.log(`${Object.keys(manifest).length} icons available, ${missing.length} without a usable icon.`);
if (missing.length) console.log(`Monogram fallback: ${missing.join(", ")}`);
